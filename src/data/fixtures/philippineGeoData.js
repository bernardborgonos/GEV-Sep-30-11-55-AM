/**
 * Resolve coordinates for a Philippine office or location using address and name text.
 * @param {string} name
 * @param {string} address
 * @returns {{ lat: number, lon: number } | null}
 */
export function lookupPhilippineCoordinates(name = '', address = '') {
  const combined = `${name} ${address}`.toLowerCase();

  // Quick NAIA general match
  if (combined.includes('naia') || combined.includes('ninoy aquino')) {
    return { lat: 14.5207, lon: 121.0152 };
  }

  // 1. Direct airport port check
  for (const port of PH_PORTS_OF_ENTRY) {
    if (combined.includes(port.code.toLowerCase()) || combined.includes(port.name.toLowerCase().split('(')[0].trim())) {
      return { lat: port.lat, lon: port.lon };
    }
  }

  // 2. Specific city/location match
  for (const [key, coords] of Object.entries(PH_KNOWN_OFFICE_COORDS)) {
    if (combined.includes(key)) {
      return { lat: coords.lat, lon: coords.lon };
    }
  }

  return null;
}
