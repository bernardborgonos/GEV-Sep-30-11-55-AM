export function buildPhilippineStrategicSimulationGeoJSON() {
  const features = PH_STRATEGIC_SIMULATION_NODES.map((node) => ({
    type: 'Feature',
    id: node.id,
    geometry: {
      type: 'Point',
      coordinates: [node.lon, node.lat],
    },
    properties: {
      name: node.name,
      category: node.category,
      operationalTier: node.operationalTier,
      jurisdictionLevel: node.jurisdictionLevel,
      islandGroup: node.islandGroup,
      region: node.region,
      regionName: node.regionName,
      province: node.province,
      city: node.city,
      address: node.address,
      contact: node.contact,
      readinessScore: node.readinessScore,
      telemetryStatus: node.telemetryStatus,
      patrolAssets: node.patrolAssets,
      semanticTags: node.semanticTags,
      country: 'Philippines',
    },
  }));

  return JSON.stringify(
    {
      type: 'FeatureCollection',
      name: 'Philippine_National_Strategic_Operational_Network',
      metadata: {
        phase: 'Phase 4',
        title: 'Philippine National Strategic Network & Operational Simulation',
        generatedAt: '2026-09-15T00:00:00Z',
        totalNodes: PH_STRATEGIC_SIMULATION_NODES.length,
        regionsCovered: 17,
        islandGroups: ['Luzon', 'Visayas', 'Mindanao'],
      },
      features,
    },
    null,
    2
  );
}

/**
 * Builds RFC 4180 CSV representation of the Phase 4 preset.
 */
export function buildPhilippineStrategicSimulationCSV() {
  const headers = [
    'ID',
    'Name',
    'Category',
    'OperationalTier',
    'JurisdictionLevel',
    'IslandGroup',
    'Region',
    'RegionName',
    'Province',
    'City',
    'Latitude',
    'Longitude',
    'ReadinessScore',
    'TelemetryStatus',
    'PatrolAssets',
    'Contact',
    'Address',
    'SemanticTags',
  ];

  const escapeCSV = (val) => {
    if (val === null || val === undefined) return '""';
    const str = String(val).replace(/"/g, '""');
    return `"${str}"`;
  };

  const rows = PH_STRATEGIC_SIMULATION_NODES.map((node) => [
    escapeCSV(node.id),
    escapeCSV(node.name),
    escapeCSV(node.category),
    escapeCSV(node.operationalTier),
    escapeCSV(node.jurisdictionLevel),
    escapeCSV(node.islandGroup),
    escapeCSV(node.region),
    escapeCSV(node.regionName),
    escapeCSV(node.province),
    escapeCSV(node.city),
    node.lat,
    node.lon,
    node.readinessScore,
    escapeCSV(node.telemetryStatus),
    node.patrolAssets,
    escapeCSV(node.contact),
    escapeCSV(node.address),
    escapeCSV(node.semanticTags.join('; ')),
  ]);

  return [headers.join(','), ...rows.map((r) => r.join(','))].join('\n');
}

export const PH_STRATEGIC_SIMULATION_GEOJSON = buildPhilippineStrategicSimulationGeoJSON();
export const PH_STRATEGIC_SIMULATION_CSV = buildPhilippineStrategicSimulationCSV();
